// Change 4 moves the preview above the bar (z-20): it lives in the gutter, so it never covers text.

"use client";

import { useEffect, useRef, useState } from "react";
import type { MouseEvent as ReactMouseEvent, ReactNode } from "react";
import gsap from "gsap";

export interface InteractiveListItem {
  client: string;
  platform?: string;
  status?: string;
  services: string | ReactNode;
  /** Image URL for the hover card. Ignored when `preview` is set. */
  img?: string;
  /** Inline SVG markup for the hover card; trusted, generated by this app. */
  preview?: string;
  /** Let the meta cell extend across the gutter (for rows whose meta is long and have no preview). */
  spanGutter?: boolean;
}

export interface InteractiveListPreviewProps {
  items?: InteractiveListItem[];
  /** Scale multiplier for the hover preview card. */
  imageSize?: number;
  /** Preview image reveal / hide duration (seconds). */
  duration?: number;
  /** Highlight bar + row text transition smoothing (seconds). */
  smoothness?: number;
  /** Pointer-follow smoothing; higher tracks faster. */
  lerp?: number;
  /** Background color of the list surface. */
  bgColor?: string;
  className?: string;
  onSelect?: (index: number) => void;
}

