//   4. the preview is an opaque card (hairline, shadow) at its natural pixel size that follows
//      the cursor, sitting to the right of it and vertically centred on it, flipped to the left
//      when it would run past the list's edge and clamped to the list and the viewport so it is
//      never cut off. It paints above the rows (z-20) so it is always legible. Below lg and on
//      touch it is not rendered. `item.spanGutter` is kept for the attack preview row's colspan.
//   5. `item.preview` (SVG markup) is inlined instead of loaded through <img>, so chart text can
//      use the page's web font.
// Plus, as the prompt instructs ("Fill image assets with Unsplash stock images you know exist"),
// the DEFAULT_ITEMS base64 JPEGs are replaced by Unsplash URLs.
//
